#%% Imports
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import scale
from sklearn.model_selection import train_test_split
from sklearn.linear_model import Ridge, RidgeCV, Lasso, LassoCV

# %% Initialisation
df = pd.read_csv("Hitters.csv")
df = df.dropna().drop("Player", axis=1) #Axis=1 means columns
# features = ['Player', 'AtBat', 'Hits', 'HmRun', 'Runs', 'RBI', 'Walks', 'Years',
#        'CAtBat', 'CHits', 'CHmRun', 'CRuns', 'CRBI', 'CWalks', 'League',
#        'Division', 'PutOuts', 'Assists', 'Errors', 'Salary', 'NewLeague']
# Setup dummies for categorical variables
dummies = pd.get_dummies(df[["League", "Division", "NewLeague"]])
#%% Setup
y = df.Salary
Xintermediate = df.drop(["League", "Division", "NewLeague", "Salary"], axis=1)
X = pd.concat([Xintermediate, dummies[["League_N", "Division_W", "NewLeague_N"]]], axis=1)
alphas = 10**(np.linspace(10, -2,100)*0.5) 
#%% Beginning methods
ridge = Ridge()
coefs = []

for a in alphas:
    ridge.set_params(alpha=a)
    ridge.fit(scale(X), y)
    ## Appends coefficients generated by the method
    coefs.append(ridge.coef_)
np.shape(coefs) #100 alphas, 19 columns
#%% Plotting Rudge
## Show the number of coefficients for each vairable (each colour)
## Each of the 19 lines is one feature’s coefficient as a function of alpha
## Instead of using OLS regression, we are using ridge regression 
ax=plt.gca()
ax.plot(alphas,coefs)
ax.set_xscale("log")
plt.xlabel("Alphas")
plt.ylabel("Coefficients")
#%%
X_train, x_test, y_train, y_test = train_test_split(X, y, test_size=5, random_state=1)